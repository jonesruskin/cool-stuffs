// helper: mirror a pose left/right (for alternate combos)
export function mirror(p) {
  const fx = v => v && [-v[0], v[1], v[2]];
  const fe = v => v && [v[0], -v[1], -v[2]];
  const fl = s => s && { ...s, u: fx(s.u), l: fx(s.l), h: fe(s.h), f: fe(s.f), tw: s.tw && -s.tw };
  return { ...p, hip: p.hip && [-p.hip[0], p.hip[1], p.hip[2]], hr: fe(p.hr), sp: fe(p.sp), ch: fe(p.ch), uc: fe(p.uc), nk: fe(p.nk), hd: fe(p.hd),
    la: fl(p.ra), ra: fl(p.la), ll: fl(p.rl), rl: fl(p.ll), L: p.R, R: p.L };
}
